import Foundation

/// Which copy of each duplicate set is kept by default.
enum KeepRule: String, CaseIterable, Identifiable, Sendable {
    case folderA = "Keep the copy in Folder A"
    case folderB = "Keep the copy in Folder B"
    case oldest = "Keep the oldest"
    case newest = "Keep the newest"
    case shortestPath = "Keep the shortest path"

    var id: String { rawValue }

    static func defaultRule(twoFolders: Bool) -> KeepRule { twoFolders ? .folderA : .shortestPath }

    /// Rules that make sense for a result (the folder rules need two folders).
    static func available(twoFolders: Bool) -> [KeepRule] {
        twoFolders ? allCases : [.shortestPath, .oldest, .newest]
    }

    /// The copy this rule keeps. Ties (and sets without a copy in the preferred folder) fall back
    /// to the shortest path, then alphabetical order, so the choice is always deterministic.
    func keeper(in group: DupGroup) -> DupFile {
        func shortest(_ files: [DupFile]) -> DupFile {
            files.min { ($0.path.count, $0.path) < ($1.path.count, $1.path) }!
        }
        let files = group.files
        switch self {
        case .folderA:
            let a = files.filter { $0.side == .a }
            return shortest(a.isEmpty ? files : a)
        case .folderB:
            let b = files.filter { $0.side == .b }
            return shortest(b.isEmpty ? files : b)
        case .oldest:
            let t = files.map(\.mtime).min()!
            return shortest(files.filter { $0.mtime == t })
        case .newest:
            let t = files.map(\.mtime).max()!
            return shortest(files.filter { $0.mtime == t })
        case .shortestPath:
            return shortest(files)
        }
    }

    /// Paths marked for removal: every copy except the keeper, in every set.
    func removals(for groups: [DupGroup]) -> Set<String> {
        var out = Set<String>()
        for g in groups {
            let keep = keeper(in: g).path
            for f in g.files where f.path != keep { out.insert(f.path) }
        }
        return out
    }
}

/// Splits a set into the copies kept and removed under `removals`, never removing every copy:
/// if all are marked, the first one is kept anyway.
func partition(_ group: DupGroup, removals: Set<String>) -> (keep: [DupFile], remove: [DupFile]) {
    var keep = group.files.filter { !removals.contains($0.path) }
    var remove = group.files.filter { removals.contains($0.path) }
    if keep.isEmpty, let first = remove.first {
        keep = [first]
        remove.removeFirst()
    }
    return (keep, remove)
}

/// Generates a bash script that moves the copies marked for removal to the Trash.
/// DiskScope never deletes duplicates itself: the user reviews the script and runs it.
enum RemovalScript {
    /// A single-quoted shell literal. Inside single quotes nothing is special except the quote
    /// itself, which becomes '\'' — safe for any path (paths can't contain NUL).
    static func shellQuote(_ s: String) -> String {
        "'" + s.replacingOccurrences(of: "'", with: "'\\''") + "'"
    }

    /// Text that's safe inside a `#` comment: one line, no control or bidi characters.
    static func commentSafe(_ s: String) -> String { Format.displaySafe(s) }

    static func make(groups: [DupGroup], removals: Set<String>, generated: Date, folders: [String]) -> String {
        let sets = groups.map { (group: $0, parts: partition($0, removals: removals)) }.filter { !$0.parts.remove.isEmpty }
        let fileCount = sets.reduce(0) { $0 + $1.parts.remove.count }
        let bytes = sets.reduce(Int64(0)) { $0 + Int64($1.parts.remove.count) * $1.group.size }
        let stamp = commentSafe(generated.formatted(date: .long, time: .shortened))

        var out = """
        #!/bin/bash
        # Duplicate removal script generated by DiskScope on \(stamp)

        """
        for (i, folder) in folders.enumerated() {
            out += "# Folder \(i == 0 ? "A" : "B"): \(commentSafe(folder))\n"
        }
        out += """
        # \(fileCount) \(fileCount == 1 ? "file" : "files") in \(sets.count) duplicate \(sets.count == 1 ? "set" : "sets") \
        marked for removal (about \(Format.bytes(bytes)) would be freed).
        #
        # Nothing is deleted permanently: files are moved to the Trash.
        # Review this script, then run it in Terminal:
        #   bash remove-duplicates.sh            dry run: shows what it would do, changes nothing
        #   bash remove-duplicates.sh --apply    moves the files marked for removal to the Trash
        #
        # Before moving a file, the script checks that both it and the copy being kept are still
        # regular files (not symbolic links) with the expected size and SHA-256 checksum.
        # Anything that changed since DiskScope compared it is skipped.

        set -euo pipefail

        APPLY=0
        case "${1:-}" in
          --apply) APPLY=1 ;;
          "") ;;
          *) printf 'usage: bash %s [--apply]\\n' "$0" >&2; exit 2 ;;
        esac

        moved=0
        would=0
        skipped=0

        skip() {
          printf 'SKIP: %s (%s)\\n' "$1" "$2"
          skipped=$((skipped + 1))
        }

        # check FILE SIZE SHA256: prints why FILE isn't that exact file any more, and fails.
        check() {
          local f="$1" size="$2" sum="$3" actual
          if [ -L "$f" ]; then echo "it is now a symbolic link"; return 1; fi
          if [ ! -f "$f" ]; then echo "it no longer exists or is not a regular file"; return 1; fi
          actual=$(/usr/bin/stat -f %z "$f") || { echo "it can't be read"; return 1; }
          if [ "$actual" != "$size" ]; then echo "its size changed"; return 1; fi
          actual=$(/usr/bin/shasum -a 256 < "$f" | /usr/bin/cut -d ' ' -f 1) || { echo "it can't be read"; return 1; }
          if [ "$actual" != "$sum" ]; then echo "its contents changed"; return 1; fi
        }

        # Moves FILE to the Trash. DISKSCOPE_TRASH_DIR, if set, is used as the Trash folder instead.
        to_trash() {
          local f="$1" dir base dest n
          if [ -z "${DISKSCOPE_TRASH_DIR:-}" ] && [ -x /usr/bin/trash ]; then
            /usr/bin/trash -s "$f" > /dev/null
            return
          fi
          dir="${DISKSCOPE_TRASH_DIR:-$HOME/.Trash}"
          /bin/mkdir -p "$dir"
          base=$(/usr/bin/basename "$f")
          dest="$dir/$base"
          n=2
          while [ -e "$dest" ] || [ -L "$dest" ]; do
            dest="$dir/$base ($n)"
            n=$((n + 1))
          done
          /bin/mv -n "$f" "$dest"
          [ ! -e "$f" ] && [ ! -L "$f" ]
        }

        # remove_copy FILE KEPT SIZE SHA256
        remove_copy() {
          local f="$1" kept="$2" size="$3" sum="$4" why
          if ! why=$(check "$f" "$size" "$sum"); then skip "$f" "$why"; return 0; fi
          if ! why=$(check "$kept" "$size" "$sum"); then skip "$f" "the copy being kept: $why"; return 0; fi
          if [ "$APPLY" = 1 ]; then
            if to_trash "$f"; then
              printf 'moved to Trash: %s\\n' "$f"
              moved=$((moved + 1))
            else
              skip "$f" "it couldn't be moved to the Trash"
            fi
          else
            printf 'would move to Trash: %s\\n' "$f"
            would=$((would + 1))
          fi
        }


        """
        for (i, entry) in sets.enumerated() {
            let g = entry.group
            out += "# Set \(i + 1) of \(sets.count) · \(Format.bytes(g.size)) each · SHA-256 \(g.digest)\n"
            for k in entry.parts.keep { out += "#   keep:   \(commentSafe(k.path))\n" }
            for r in entry.parts.remove { out += "#   remove: \(commentSafe(r.path))\n" }
            let kept = shellQuote(entry.parts.keep[0].path)
            for r in entry.parts.remove {
                out += "remove_copy \(shellQuote(r.path)) \(kept) \(g.size) \(g.digest)\n"
            }
            out += "\n"
        }
        out += """
        echo
        if [ "$APPLY" = 1 ]; then
          echo "Done: $moved moved to the Trash, $skipped skipped."
        else
          echo "Dry run: $would would be moved to the Trash, $skipped skipped. Nothing was changed."
          echo "Run again with --apply to move them to the Trash."
        fi

        """
        return out
    }
}

/// CSV export of duplicate sets: one row per copy.
enum DuplicatesCSV {
    static let header = ["set", "sha256", "size_bytes", "copies", "wasted_bytes", "side", "plan", "path", "modified"]

    static func make(groups: [DupGroup], removals: Set<String>) -> String {
        var out = CSV.row(header)
        for (i, g) in groups.enumerated() {
            let parts = partition(g, removals: removals)
            let removed = Set(parts.remove.map(\.path))
            for f in g.files {
                out += CSV.row(encoded: [
                    CSV.number(i + 1), CSV.field(g.digest), CSV.number(g.size), CSV.number(g.copies),
                    CSV.number(g.wasted), CSV.field(f.side.label), CSV.field(removed.contains(f.path) ? "remove" : "keep"),
                    CSV.field(f.path), CSV.field(f.modified.formatted(.iso8601)),
                ])
            }
        }
        return out
    }
}
